def save_psd_diagnostic_multipanel_plot(
    dtm: np.ndarray,
    pixel_scale_m: float,
    output_path: Path,
    title: str,
    max_display_percentile: float = 99.0,
) -> None:
    """Save DTM, 2D FFT power, and radially averaged PSD diagnostics."""
    dtm = np.asarray(dtm, dtype=float)
    finite_mask = np.isfinite(dtm)
    if not np.any(finite_mask):
        raise ValueError("DTM has no finite values for PSD diagnostic plot.")

    dtm_clean = dtm.copy()
    dtm_clean[~finite_mask] = np.nanmedian(dtm_clean[finite_mask])
    dtm_zero_mean = dtm_clean - np.mean(dtm_clean)

    nrows, ncols = dtm_zero_mean.shape
    fft_2d = np.fft.fftshift(np.fft.fft2(dtm_zero_mean))
    power_2d = np.abs(fft_2d) ** 2
    power_display = np.log10(power_2d + 1e-12)

    freq_y = np.fft.fftshift(np.fft.fftfreq(nrows, d=pixel_scale_m))
    freq_x = np.fft.fftshift(np.fft.fftfreq(ncols, d=pixel_scale_m))
    fx, fy = np.meshgrid(freq_x, freq_y)
    radial_frequency = np.sqrt(fx**2 + fy**2).ravel()
    power_flat = power_2d.ravel()

    valid = (
        np.isfinite(radial_frequency)
        & np.isfinite(power_flat)
        & (radial_frequency > 0)
        & (power_flat > 0)
    )
    radial_frequency = radial_frequency[valid]
    power_flat = power_flat[valid]

    if radial_frequency.size == 0:
        raise ValueError("No valid positive frequencies for PSD diagnostic.")

    n_bins = 80
    freq_bins = np.logspace(
        np.log10(radial_frequency.min()),
        np.log10(radial_frequency.max()),
        n_bins + 1,
    )
    freq_centers = np.sqrt(freq_bins[:-1] * freq_bins[1:])
    psd_1d = np.full(n_bins, np.nan)
    counts = np.zeros(n_bins, dtype=int)

    for index in range(n_bins):
        in_bin = (
            (radial_frequency >= freq_bins[index])
            & (radial_frequency < freq_bins[index + 1])
        )
        counts[index] = np.count_nonzero(in_bin)
        if counts[index] > 0:
            psd_1d[index] = np.mean(power_flat[in_bin])

    valid_1d = np.isfinite(psd_1d) & (psd_1d > 0) & (counts > 0)

    fig, axes = plt.subplots(1, 3, figsize=(15, 4.8))

    vmin = np.nanpercentile(dtm_clean, 100 - max_display_percentile)
    vmax = np.nanpercentile(dtm_clean, max_display_percentile)
    im0 = axes[0].imshow(
        dtm_clean, origin="upper", cmap="gray", vmin=vmin, vmax=vmax
    )
    axes[0].set_title("Detrended DTM")
    axes[0].set_xlabel("Sample")
    axes[0].set_ylabel("Line")
    fig.colorbar(im0, ax=axes[0], fraction=0.046, pad=0.04).set_label(
        "Elevation residual (m)"
    )

    im1 = axes[1].imshow(power_display, origin="upper", cmap="viridis")
    axes[1].set_title("2D Power Spectrum")
    axes[1].set_xlabel("Frequency x")
    axes[1].set_ylabel("Frequency y")
    fig.colorbar(im1, ax=axes[1], fraction=0.046, pad=0.04).set_label(
        "log10(Power)"
    )

    axes[2].loglog(freq_centers[valid_1d], psd_1d[valid_1d], "-", linewidth=1.8)
    axes[2].set_title("1D Radially Averaged PSD")
    axes[2].set_xlabel("Spatial frequency (1/m)")
    axes[2].set_ylabel("Power")
    axes[2].grid(True, which="both", alpha=0.3)

    fig.suptitle(title, fontsize=14)
    fig.tight_layout()
    fig.savefig(output_path, dpi=300)
    plt.close(fig)


