def clean_text(value: Any) -> str:
    """Return a safe stripped string for catalog values."""
    return "" if value is None else str(value).strip()


def normalize_catalog_header(header: Any) -> str:
    """Normalize a CSV header for matching historical spelling variants."""
    text = clean_text(header).replace("\ufeff", "")
    text = re.sub(r"\s+", " ", text)
    return re.sub(r"[^a-z0-9]+", "", text.casefold())


CATALOG_HEADER_ALIASES = {
    normalize_catalog_header("ROI_ID"): "ROI_ID",
    normalize_catalog_header("Source CUB"): "Source CUB",
    normalize_catalog_header("Source TIFF"): "Source TIFF",
    normalize_catalog_header("X"): "X",
    normalize_catalog_header("Y"): "Y",
    normalize_catalog_header("Width"): "Width",
    normalize_catalog_header("Height"): "Height",
    normalize_catalog_header("Pixel Scale m/pixel"): "Pixel Scale m/pixel",
    normalize_catalog_header("QC Status"): "QC Status",
    normalize_catalog_header("roi_shape"): "roi_shape",
    normalize_catalog_header("rotation_deg"): "rotation_deg",
    normalize_catalog_header("Display Rotation Degrees"): "Display Rotation Degrees",
    normalize_catalog_header("Rotated Corners Original Image"): "Rotated Corners Original Image",
    normalize_catalog_header("Bounding Box X"): "Bounding Box X",
    normalize_catalog_header("Bounding Box Y"): "Bounding Box Y",
    normalize_catalog_header("Bounding Box Width"): "Bounding Box Width",
    normalize_catalog_header("Bounding Box Height"): "Bounding Box Height",
    normalize_catalog_header("Rotated Width Pixels"): "Rotated Width Pixels",
    normalize_catalog_header("Rotated Height Pixels"): "Rotated Height Pixels",
    normalize_catalog_header("Rotated DTM NPY"): "Rotated DTM NPY",
    normalize_catalog_header("Selected by"): "Selected By",
    normalize_catalog_header("Dsplay Scale"): "Display Scale",
}


def canonical_catalog_header(header: Any) -> str:
    """Return the canonical header name used by the analysis workflow."""
    cleaned = clean_text(header).replace("\ufeff", "")
    return CATALOG_HEADER_ALIASES.get(normalize_catalog_header(cleaned), cleaned)


def resolve_project_path(value: Any, repo_root: Path | None = None) -> Path | None:
    """Resolve an absolute or repository-relative catalog path."""
    text = clean_text(value)
    if not text:
        return None

    path = Path(text).expanduser()
    if path.is_absolute():
        return path

    root = Path(repo_root) if repo_root is not None else REPO_ROOT
    return (root / path).resolve()


def load_roi_catalog_row(roi_id: str) -> dict[str, str]:
    """Load one ROI row while safely handling duplicate legacy headers."""
    if not ROI_CATALOG.exists():
        raise FileNotFoundError(f"Could not find ROI catalog: {ROI_CATALOG}")

    target_id = clean_text(roi_id)
    with ROI_CATALOG.open("r", newline="", encoding="utf-8-sig") as handle:
        rows = list(csv.reader(handle))

    if not rows:
        raise ValueError(f"ROI catalog is empty: {ROI_CATALOG}")

    raw_headers = rows[0]
    for values in rows[1:]:
        row: dict[str, str] = {}

        for index, raw_header in enumerate(raw_headers):
            header = canonical_catalog_header(raw_header)
            if not header:
                continue

            value = clean_text(values[index] if index < len(values) else "")
            if header not in row or (not clean_text(row[header]) and value):
                row[header] = value

        if clean_text(row.get("ROI_ID")) == target_id:
            return row

    raise ValueError(f"ROI_ID not found in catalog: {roi_id}")


def list_roi_ids() -> list[str]:
    """Return nonblank ROI IDs from the configured catalog in file order."""
    if not ROI_CATALOG.exists():
        raise FileNotFoundError(f"Could not find ROI catalog: {ROI_CATALOG}")

    ids: list[str] = []
    with ROI_CATALOG.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        for raw_row in reader:
            row = {canonical_catalog_header(k): v for k, v in raw_row.items() if k}
            roi_id = clean_text(row.get("ROI_ID"))
            if roi_id and roi_id not in ids:
                ids.append(roi_id)
    return ids


def safe_float(value: Any) -> float | None:
    """Convert a value to float, returning None for blank/unknown values."""
    text = clean_text(value)
    if not text or text.casefold() in {"unknown", "none"}:
        return None
    return float(text)


def safe_optional_int(value: Any) -> int | None:
    """Convert a possibly blank catalog field to int."""
    text = clean_text(value)
    return int(float(text)) if text else None


def first_available_int(*values: Any) -> int | None:
    """Return the first nonblank integer among candidate values."""
    for value in values:
        converted = safe_optional_int(value)
        if converted is not None:
            return converted
    return None


def prepare_roi_geometry_for_analysis(
    row: dict[str, Any],
    repo_root: Path | None = None,
) -> dict[str, Any]:
    """Interpret the axis-aligned-versus-rotated ROI catalog schema."""
    warnings: list[str] = []

    raw_shape = clean_text(row.get("roi_shape")).lower()
    rotated_dtm_npy = clean_text(row.get("Rotated DTM NPY"))

    rotation_deg = safe_float(row.get("rotation_deg"))
    if rotation_deg is None:
        rotation_deg = safe_float(row.get("Display Rotation Degrees"))
    if rotation_deg is None:
        rotation_deg = 0.0

    if not raw_shape:
        if rotated_dtm_npy and abs(rotation_deg) > 1e-6:
            roi_shape = "rotated_rect"
            warnings.append(
                "Legacy row has no roi_shape; inferred rotated_rect from "
                "nonzero rotation plus Rotated DTM NPY."
            )
        else:
            roi_shape = "axis_aligned_rect"
            warnings.append(
                "Legacy row has no roi_shape; treated as axis_aligned_rect."
            )
    elif raw_shape in {"axis_aligned_rect", "rotated_rect"}:
        roi_shape = raw_shape
    else:
        raise ValueError(
            f"Unsupported roi_shape {raw_shape!r}; expected "
            "'axis_aligned_rect' or 'rotated_rect'."
        )

    if roi_shape == "rotated_rect":
        if not rotated_dtm_npy:
            raise ValueError(
                "ROI is rotated_rect but 'Rotated DTM NPY' is blank."
            )

        rotated_dtm_path = resolve_project_path(rotated_dtm_npy, repo_root)
        assert rotated_dtm_path is not None
        if not rotated_dtm_path.exists():
            raise FileNotFoundError(
                f"Rotated science DTM does not exist: {rotated_dtm_path}"
            )

        analysis_width = safe_optional_int(row.get("Rotated Width Pixels"))
        analysis_height = safe_optional_int(row.get("Rotated Height Pixels"))
        if analysis_width is None or analysis_height is None:
            raise ValueError(
                "rotated_rect requires Rotated Width Pixels and "
                "Rotated Height Pixels."
            )

        bbox_x = first_available_int(row.get("Bounding Box X"), row.get("X"))
        bbox_y = first_available_int(row.get("Bounding Box Y"), row.get("Y"))
        bbox_width = first_available_int(
            row.get("Bounding Box Width"), row.get("Width")
        )
        bbox_height = first_available_int(
            row.get("Bounding Box Height"), row.get("Height")
        )

        if abs(rotation_deg) <= 1e-6:
            warnings.append(
                "roi_shape is rotated_rect but rotation is zero/blank; "
                "the explicit rotated .npy remains the science input."
            )

        return {
            "roi_shape": roi_shape,
            "rotation_deg": float(rotation_deg),
            "input_mode": "pre_extracted_rotated_npy",
            "is_rotated_roi": True,
            "analysis_width_pixels": int(analysis_width),
            "analysis_height_pixels": int(analysis_height),
            "rotated_dtm_npy": str(rotated_dtm_path),
            "catalog_crop_x": bbox_x,
            "catalog_crop_y": bbox_y,
            "catalog_crop_width": bbox_width,
            "catalog_crop_height": bbox_height,
            "warnings": warnings,
        }

    x = safe_optional_int(row.get("X"))
    y = safe_optional_int(row.get("Y"))
    width = safe_optional_int(row.get("Width"))
    height = safe_optional_int(row.get("Height"))

    missing = [
        name
        for name, value in {
            "X": x,
            "Y": y,
            "Width": width,
            "Height": height,
        }.items()
        if value is None
    ]
    if missing:
        raise ValueError(
            "axis_aligned_rect is missing required crop fields: "
            + ", ".join(missing)
        )

    if rotated_dtm_npy:
        warnings.append(
            "Axis-aligned ROI contains a Rotated DTM NPY; it is ignored."
        )

    rotated_metadata_present = any(
        clean_text(row.get(field))
        for field in (
            "Rotated Corners Original Image",
            "Bounding Box X",
            "Bounding Box Y",
            "Bounding Box Width",
            "Bounding Box Height",
            "Rotated Width Pixels",
            "Rotated Height Pixels",
        )
    )
    if rotated_metadata_present:
        warnings.append(
            "Axis-aligned ROI contains rotated metadata; those fields are "
            "ignored for analysis."
        )

    if abs(rotation_deg) > 1e-6:
        warnings.append(
            "Axis-aligned ROI has a nonzero catalog rotation; roi_shape takes "
            "precedence and the ROI is analyzed as axis-aligned."
        )

    return {
        "roi_shape": roi_shape,
        "rotation_deg": float(rotation_deg),
        "input_mode": "isis_cub_crop_ascii",
        "is_rotated_roi": False,
        "analysis_width_pixels": int(width),
        "analysis_height_pixels": int(height),
        "rotated_dtm_npy": "",
        "catalog_crop_x": int(x),
        "catalog_crop_y": int(y),
        "catalog_crop_width": int(width),
        "catalog_crop_height": int(height),
        "warnings": warnings,
    }


