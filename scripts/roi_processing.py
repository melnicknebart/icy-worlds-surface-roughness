def evaluate_raw_dtm_quality(raw_dtm: np.ndarray) -> dict[str, Any]:
    """Evaluate missing/null pixels in a raw DTM."""
    null_mask = (~np.isfinite(raw_dtm)) | (raw_dtm <= NULL_THRESHOLD)

    bad_pixel_count = int(null_mask.sum())
    total_pixel_count = int(raw_dtm.size)
    if total_pixel_count == 0:
        raise ValueError("Raw DTM contains zero pixels.")

    bad_pixel_fraction = bad_pixel_count / total_pixel_count
    row_null_fraction = null_mask.mean(axis=1)
    col_null_fraction = null_mask.mean(axis=0)

    large_null_region = bool(
        row_null_fraction.max() > 0.5 or col_null_fraction.max() > 0.5
    )

    if large_null_region:
        qc_status = "Reject"
        qc_notes = (
            "Large contiguous null-data region detected. "
            "Reselect away from the DTM coverage boundary."
        )
    elif bad_pixel_fraction < GOOD_MAX_BAD_FRACTION:
        qc_status = "Good"
        qc_notes = "Very low bad-pixel fraction."
    elif bad_pixel_fraction < QUESTIONABLE_MAX_BAD_FRACTION:
        qc_status = "Questionable"
        qc_notes = "Small bad-pixel fraction; usable with caution."
    elif bad_pixel_fraction < NEEDS_REVIEW_MAX_BAD_FRACTION:
        qc_status = "Needs Review"
        qc_notes = "Moderate bad-pixel fraction; inspect before final use."
    else:
        qc_status = "Reject"
        qc_notes = "Bad-pixel fraction is too high."

    return {
        "bad_pixel_count": bad_pixel_count,
        "total_pixel_count": total_pixel_count,
        "bad_pixel_fraction": bad_pixel_fraction,
        "large_null_region": large_null_region,
        "qc_status": qc_status,
        "qc_notes": qc_notes,
    }


def clean_dtm_with_median_filter(
    raw_dtm: np.ndarray,
    qc_info: dict[str, Any],
) -> tuple[np.ndarray, dict[str, Any]]:
    """Fill small isolated null pixels using a local median-filter estimate."""
    dtm = raw_dtm.astype(np.float64).copy()
    bad_mask = (~np.isfinite(dtm)) | (dtm <= NULL_THRESHOLD)

    if bad_mask.sum() == 0:
        return dtm, {
            "cleaning_method": "none",
            "cleaning_notes": "No null pixels found.",
        }

    if qc_info["bad_pixel_fraction"] >= NEEDS_REVIEW_MAX_BAD_FRACTION:
        raise ValueError(
            "Bad-pixel fraction is too high for the small-gap median-filter "
            "cleaning path."
        )

    valid_values = dtm[~bad_mask & np.isfinite(dtm)]
    if valid_values.size == 0:
        raise ValueError("No valid pixels found in raw DTM.")

    dtm_for_filter = dtm.copy()
    dtm_for_filter[bad_mask] = np.median(valid_values)
    filtered = median_filter(dtm_for_filter, size=MEDIAN_FILTER_SIZE)

    cleaned = dtm.copy()
    cleaned[bad_mask] = filtered[bad_mask]

    return cleaned, {
        "cleaning_method": "median_filter",
        "median_filter_size": MEDIAN_FILTER_SIZE,
        "cleaning_notes": (
            "Null pixels were replaced with local median-filtered values. "
            "This path is intended for small isolated gaps."
        ),
    }


def interpolate_missing_pixels(
    raw_dtm: np.ndarray,
    qc_info: dict[str, Any],
    method: str = "linear_then_nearest",
) -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    """Interpolate missing pixels while preserving an explicit interpolation mask."""
    del qc_info  # retained in the signature for compatibility/provenance

    dtm = raw_dtm.astype(np.float64).copy()
    bad_mask = (~np.isfinite(dtm)) | (dtm <= NULL_THRESHOLD)
    good_mask = ~bad_mask & np.isfinite(dtm)

    bad_pixel_count = int(bad_mask.sum())
    total_pixel_count = int(dtm.size)

    if bad_pixel_count == 0:
        return dtm, bad_mask, {
            "cleaning_method": "none",
            "interpolation_method": None,
            "interpolated_pixel_count": 0,
            "interpolated_fraction": 0.0,
            "cleaning_notes": "No null pixels found.",
        }

    if good_mask.sum() == 0:
        raise ValueError("Cannot interpolate because no valid pixels exist.")

    y_grid, x_grid = np.indices(dtm.shape)
    good_points = np.column_stack((x_grid[good_mask], y_grid[good_mask]))
    good_values = dtm[good_mask]
    bad_points = np.column_stack((x_grid[bad_mask], y_grid[bad_mask]))

    cleaned = dtm.copy()

    if method == "nearest":
        values = griddata(good_points, good_values, bad_points, method="nearest")
        cleaned[bad_mask] = values

    elif method == "linear_then_nearest":
        linear_values = griddata(
            good_points, good_values, bad_points, method="linear"
        )
        nearest_values = griddata(
            good_points, good_values, bad_points, method="nearest"
        )
        final_values = linear_values.copy()
        missing_linear = ~np.isfinite(final_values)
        final_values[missing_linear] = nearest_values[missing_linear]
        cleaned[bad_mask] = final_values

    elif method == "nearest_then_median":
        nearest_values = griddata(
            good_points, good_values, bad_points, method="nearest"
        )
        cleaned[bad_mask] = nearest_values
        smoothed = median_filter(cleaned, size=MEDIAN_FILTER_SIZE)
        cleaned[bad_mask] = smoothed[bad_mask]

    else:
        raise ValueError(f"Unknown interpolation method: {method}")

    if not np.all(np.isfinite(cleaned[bad_mask])):
        raise ValueError(
            "Interpolation left non-finite values in previously missing pixels."
        )

    distance_to_valid = distance_transform_edt(bad_mask)
    distances = distance_to_valid[bad_mask]

    return cleaned, bad_mask, {
        "cleaning_method": "interpolation",
        "interpolation_method": method,
        "interpolated_pixel_count": bad_pixel_count,
        "total_pixel_count": total_pixel_count,
        "interpolated_fraction": bad_pixel_count / total_pixel_count,
        "max_interpolation_distance_pixels": float(distances.max()),
        "mean_interpolation_distance_pixels": float(distances.mean()),
        "mentor_approved_interpolation": True,
        "cleaning_notes": (
            "Missing pixels were interpolated. Interpolation can suppress "
            "roughness and alter PSD/breakpoint behavior, so these ROIs should "
            "be interpreted cautiously."
        ),
    }


