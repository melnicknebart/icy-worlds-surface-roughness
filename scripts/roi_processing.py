#!/usr/bin/env python3
"""Reusable ROI preprocessing, quality-control, detrending, and PSD utilities.

This module contains the non-Hurst parts of the icy-worlds roughness workflow.
It is imported by ``run_roi_analysis_multibody.py`` and is not intended to be
run directly.

The catalog written by the OpenCV ROI selector stores image coordinates using
zero-based pixel indexing. USGS ISIS ``crop`` uses one-based SAMPLE/LINE start
coordinates, so this module explicitly converts catalog X/Y to ISIS SAMPLE/LINE
when cropping axis-aligned ROIs.

Rotated ROIs are loaded from the selector-created ``Rotated DTM NPY`` file.
That saved array is treated as the frozen science input for exact reproduction.
"""

from __future__ import annotations

import csv
import re
import shutil
import subprocess
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
from scipy.interpolate import griddata
from scipy.ndimage import distance_transform_edt, median_filter


# ---------------------------------------------------------------------------
# Runtime configuration
# ---------------------------------------------------------------------------

ROI_CATALOG = Path("catalogs/roi_catalog.csv")
OUTPUT_ROOT = Path("results/reproducible_rois")
REPO_ROOT = Path.cwd()

NULL_VALUE = -9999
NULL_THRESHOLD = -9000

GOOD_MAX_BAD_FRACTION = 0.01
QUESTIONABLE_MAX_BAD_FRACTION = 0.05
NEEDS_REVIEW_MAX_BAD_FRACTION = 0.10

SKIP_REJECTED_ROIS = True
STOP_IF_LARGE_NULL_REGION = False
MEDIAN_FILTER_SIZE = 3

ALLOW_INTERPOLATION_FOR_REJECTED_ROIS = True
INTERPOLATION_METHOD = "linear_then_nearest"
SAVE_INTERPOLATION_MASK = True

# The multibody OpenCV selector stores image pixel coordinates starting at 0.
# ISIS crop SAMPLE/LINE starts at 1. Do not change this unless your catalog was
# generated by a different tool that already stores one-based ISIS coordinates.
CATALOG_COORDINATES_ARE_ZERO_BASED = True


