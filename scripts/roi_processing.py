def detrend_plane(dtm: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Fit and subtract a least-squares best-fit plane."""
    ny, nx = dtm.shape
    x, y = np.meshgrid(np.arange(nx), np.arange(ny))

    design = np.column_stack(
        (x.ravel(), y.ravel(), np.ones(nx * ny))
    )
    z = dtm.ravel()

    coeffs, _, _, _ = np.linalg.lstsq(design, z, rcond=None)
    plane = coeffs[0] * x + coeffs[1] * y + coeffs[2]
    return dtm - plane, plane, coeffs


def power_spectrum_1d(
    dtm: np.ndarray,
    pixel_scale: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Compute a 2D FFT power spectrum and an integer-radius 1D radial average."""
    dtm_zero_mean = dtm - np.mean(dtm)

    fft = np.fft.fft2(dtm_zero_mean)
    fft_shifted = np.fft.fftshift(fft)
    power_2d = np.abs(fft_shifted) ** 2

    ny, nx = dtm.shape
    cy, cx = ny // 2, nx // 2
    y, x = np.indices((ny, nx))
    radius = np.sqrt((x - cx) ** 2 + (y - cy) ** 2).astype(int)

    radial_power = np.bincount(radius.ravel(), power_2d.ravel())
    radial_count = np.bincount(radius.ravel())
    psd_1d = radial_power / np.maximum(radial_count, 1)

    freqs = np.fft.fftfreq(nx, d=pixel_scale)
    if len(freqs) < 2:
        raise ValueError("DTM is too narrow to compute a 1D PSD frequency step.")

    freq_step = abs(freqs[1] - freqs[0])
    radial_freq = np.arange(len(psd_1d)) * freq_step
    return radial_freq[1:], psd_1d[1:], power_2d


