def make_roi_folders(roi_id: str) -> tuple[Path, Path, Path, Path]:
    """Create the standard per-ROI output folders."""
    roi_dir = OUTPUT_ROOT / roi_id
    data_dir = roi_dir / "data"
    figure_dir = roi_dir / "figures"
    log_dir = roi_dir / "logs"

    for directory in (data_dir, figure_dir, log_dir):
        directory.mkdir(parents=True, exist_ok=True)

    return roi_dir, data_dir, figure_dir, log_dir


def _require_executable(name: str) -> None:
    if shutil.which(name) is None:
        raise RuntimeError(
            f"Required USGS ISIS executable {name!r} was not found on PATH. "
            "Activate the ISIS environment before running axis-aligned ROIs."
        )


def run_command(command: list[Any], log_lines: list[str]) -> subprocess.CompletedProcess[str]:
    """Run an external command and append command/stdout/stderr to the log."""
    executable = str(command[0])
    _require_executable(executable)

    command_text = " ".join(str(part) for part in command)
    log_lines.append(f"\nCOMMAND:\n{command_text}\n")

    result = subprocess.run(
        [str(part) for part in command],
        capture_output=True,
        text=True,
        check=False,
    )

    log_lines.append("STDOUT:\n" + result.stdout)
    log_lines.append("STDERR:\n" + result.stderr)

    if result.returncode != 0:
        raise RuntimeError(
            f"Command failed with return code {result.returncode}:\n"
            f"{command_text}\n\nSTDOUT:\n{result.stdout}\n\n"
            f"STDERR:\n{result.stderr}"
        )

    return result


def catalog_xy_to_isis_sample_line(x: int, y: int) -> tuple[int, int]:
    """Convert selector catalog X/Y to ISIS SAMPLE/LINE starts."""
    if CATALOG_COORDINATES_ARE_ZERO_BASED:
        return int(x) + 1, int(y) + 1
    return int(x), int(y)


def crop_cub_with_isis(
    source_cub: Path,
    output_cub: Path,
    x: int,
    y: int,
    width: int,
    height: int,
    log_lines: list[str],
) -> None:
    """Crop a CUB using catalog geometry and explicit coordinate conversion."""
    sample, line = catalog_xy_to_isis_sample_line(x, y)
    log_lines.append(
        "Catalog-to-ISIS coordinate conversion: "
        f"X={x}, Y={y} -> SAMPLE={sample}, LINE={line}; "
        f"zero_based_catalog={CATALOG_COORDINATES_ARE_ZERO_BASED}"
    )

    command = [
        "crop",
        f"from={source_cub}",
        f"to={output_cub}",
        f"SAMPLE={sample}",
        f"LINE={line}",
        f"NSAMPLES={int(width)}",
        f"NLINES={int(height)}",
    ]
    run_command(command, log_lines)


def cub_to_ascii_with_isis(
    input_cub: Path,
    output_txt: Path,
    log_lines: list[str],
) -> None:
    """Convert a cropped ISIS CUB to an ASCII elevation grid."""
    command = [
        "isis2ascii",
        f"from={input_cub}",
        f"to={output_txt}",
        "HEADER=false",
        "SETPIXELVALUE=true",
        f"NULLVALUE={NULL_VALUE}",
    ]
    run_command(command, log_lines)


def load_ascii_dtm(txt_path: Path) -> np.ndarray:
    """Load an ISIS ASCII elevation grid into NumPy."""
    return np.loadtxt(txt_path)


def load_raw_dtm_for_roi(
    geometry: dict[str, Any],
    source_cub_path: Path | None,
    cropped_cub: Path,
    ascii_txt: Path,
    raw_dtm_path: Path,
    log_lines: list[str],
) -> tuple[np.ndarray, dict[str, Any]]:
    """Load the science DTM for either an axis-aligned or rotated ROI."""
    if geometry["is_rotated_roi"]:
        rotated_dtm_path = Path(geometry["rotated_dtm_npy"])
        log_lines.extend(
            [
                "\nRAW DTM SOURCE",
                "Using selector-created rotated science DTM.",
                f"Rotated DTM NPY: {rotated_dtm_path}",
            ]
        )

        raw_dtm = np.load(rotated_dtm_path)
        if raw_dtm.ndim != 2:
            raise ValueError(
                f"Rotated DTM must be 2D; got shape {raw_dtm.shape}."
            )

        expected_shape = (
            int(geometry["analysis_height_pixels"]),
            int(geometry["analysis_width_pixels"]),
        )
        if tuple(raw_dtm.shape) != expected_shape:
            raise ValueError(
                "Rotated DTM shape does not match catalog dimensions.\n"
                f"Expected (height, width): {expected_shape}\n"
                f"Loaded: {tuple(raw_dtm.shape)}\n"
                f"Path: {rotated_dtm_path}"
            )

        np.save(raw_dtm_path, raw_dtm)
        return raw_dtm, {
            "raw_dtm_source": "pre_extracted_rotated_npy",
            "input_mode": geometry["input_mode"],
            "roi_shape": geometry["roi_shape"],
            "rotation_deg": geometry["rotation_deg"],
            "rotated_dtm_npy": str(rotated_dtm_path),
            "used_cub_crop": False,
            "expected_shape_height_width": list(expected_shape),
        }

    if source_cub_path is None:
        raise ValueError("axis_aligned_rect requires a Source CUB.")

    log_lines.extend(
        [
            "\nRAW DTM SOURCE",
            "Using axis-aligned CUB crop workflow.",
            "Rotated DTM NPY is not used.",
        ]
    )

    crop_cub_with_isis(
        source_cub_path,
        cropped_cub,
        geometry["catalog_crop_x"],
        geometry["catalog_crop_y"],
        geometry["catalog_crop_width"],
        geometry["catalog_crop_height"],
        log_lines,
    )
    cub_to_ascii_with_isis(cropped_cub, ascii_txt, log_lines)

    raw_dtm = load_ascii_dtm(ascii_txt)
    if raw_dtm.ndim != 2:
        raise ValueError(
            f"Axis-aligned CUB crop must be 2D; got {raw_dtm.shape}."
        )

    expected_shape = (
        int(geometry["analysis_height_pixels"]),
        int(geometry["analysis_width_pixels"]),
    )
    if tuple(raw_dtm.shape) != expected_shape:
        log_lines.append(
            "WARNING: ISIS crop array shape differs from catalog geometry. "
            f"Expected {expected_shape}, loaded {tuple(raw_dtm.shape)}."
        )

    np.save(raw_dtm_path, raw_dtm)
    return raw_dtm, {
        "raw_dtm_source": "isis_cub_crop_ascii",
        "input_mode": geometry["input_mode"],
        "roi_shape": geometry["roi_shape"],
        "rotation_deg": geometry["rotation_deg"],
        "rotated_dtm_npy": "",
        "used_cub_crop": True,
        "source_cub": str(source_cub_path),
        "cropped_cub": str(cropped_cub),
        "ascii_txt": str(ascii_txt),
        "catalog_coordinates_zero_based": CATALOG_COORDINATES_ARE_ZERO_BASED,
        "expected_shape_height_width": list(expected_shape),
        "loaded_shape_height_width": list(raw_dtm.shape),
    }


